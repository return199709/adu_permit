"""Write a drawkit project folder from the owner's answers and a rule file."""
import json, os, shutil
from . import schema, check

def draw(answers, rules, outdir, allow_draft=False):
    os.makedirs(outdir, exist_ok=True)
    a = json.load(open(answers)); r = schema.load(rules)
    json.dump(a, open(os.path.join(outdir, 'answers.json'), 'w'), indent=2); json.dump(r, open(os.path.join(outdir, 'rules.json'), 'w'), indent=2, ensure_ascii=False)
    json.dump({'allow_draft': allow_draft}, open(os.path.join(outdir, 'permit.json'), 'w'))
    name = a['project']['name']
    open(os.path.join(outdir, 'project.py'), 'w').write(f'''"""Generated by permit.py draw.  Build with:  python run.py {outdir}"""
TITLE_PREFIX = {name + ' - '!r}
AUTHOR = 'drawkit.permit'
SET_NAME = {name.replace(' ', '_') + '_Permit_Set.pdf'!r}
SHEETS = [
    ('T-1', 'T-1_cover_sheet',         'generated', 'drawkit.permit.sheets.cover', 'Cover Sheet',        None),
    ('A-1', 'A-1_site_and_roof_plan',  'generated', 'drawkit.permit.sheets.site',  'Site and Roof Plan', None),
    ('A-2', 'A-2_floor_plan',          'generated', 'drawkit.permit.sheets.plan',  'Floor Plan',         None),
]
''')
    res = check.run(a, r, allow_draft); ok = check.report(res)
    print(f'project written to {outdir}; build it with:  python run.py {outdir}')
    return ok
